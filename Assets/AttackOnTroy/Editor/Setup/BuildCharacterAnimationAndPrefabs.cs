    [MenuItem(MenuRoot + "Configure Level 01 Actors")]
    private static void ConfigureLevel01Actors()
    {
        Scene scene = SceneManager.GetActiveScene();
        if (!scene.IsValid() || scene.name != "SCN_Level01_Beach")
        {
            EditorUtility.DisplayDialog("Configure Level 01 Actors", "Make SCN_Level01_Beach the active scene first. No changes were made.", "OK");
            return;
        }

        GameObject[] actorsMatches = FindSceneObjects(scene, "Actors");
        if (actorsMatches.Length != 1)
        {
            EditorUtility.DisplayDialog("Configure Level 01 Actors", "Expected exactly one Actors object in SCN_Level01_Beach; found " + actorsMatches.Length + ". No changes were made.", "OK");
            return;
        }
        Transform actors = actorsMatches[0].transform;
        Transform playerSpawn = actors.Find("PlayerSpawn");
        Transform cyclopsSpawn = actors.Find("CyclopsSpawn");
        if (playerSpawn == null || cyclopsSpawn == null)
        {
            EditorUtility.DisplayDialog("Configure Level 01 Actors", "Actors must contain PlayerSpawn and CyclopsSpawn. No changes were made.", "OK");
            return;
        }

        var specs = new[]
        {
            new { Path="Assets/AttackOnTroy/Characters/Achilles/Prefabs/PF_Achilles.prefab", Name="Player_Achilles", Spawn=playerSpawn },
            new { Path="Assets/AttackOnTroy/Enemies/CyclopsNormal/Prefabs/PF_CyclopsNormal.prefab", Name="Enemy_CyclopsNormal", Spawn=cyclopsSpawn }
        };
        foreach (var spec in specs)
        {
            GameObject prefab = AssetDatabase.LoadAssetAtPath<GameObject>(spec.Path);
            if (prefab == null)
            {
                EditorUtility.DisplayDialog("Configure Level 01 Actors", "Required prefab is missing: " + spec.Path + ". No changes were made.", "OK");
                return;
            }
            GameObject existing = null;
            foreach (Transform child in actors)
                if (child.name == spec.Name) existing = child.gameObject;
            if (existing != null && PrefabUtility.GetCorrespondingObjectFromSource(existing) != prefab)
            {
                EditorUtility.DisplayDialog("Configure Level 01 Actors", "An object named " + spec.Name + " already exists under Actors but is not the expected prefab instance. No changes were made.", "OK");
                return;
            }
        }

        int group = Undo.GetCurrentGroup();
        Undo.IncrementCurrentGroup();
        group = Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Configure Level 01 Actors");
        foreach (var spec in specs)
        {
            GameObject existing = actors.Find(spec.Name)?.gameObject;
            if (existing != null) continue;
            GameObject instance = (GameObject)PrefabUtility.InstantiatePrefab(AssetDatabase.LoadAssetAtPath<GameObject>(spec.Path), scene);
            Undo.RegisterCreatedObjectUndo(instance, "Create " + spec.Name);
            instance.name = spec.Name;
            Undo.SetTransformParent(instance.transform, actors, "Parent " + spec.Name + " under Actors");
            Undo.RecordObject(instance.transform, "Place " + spec.Name + " at spawn");
            instance.transform.SetPositionAndRotation(spec.Spawn.position, spec.Spawn.rotation);
            EditorUtility.SetDirty(instance);
        }
        EditorSceneManager.MarkSceneDirty(scene);
        Undo.CollapseUndoOperations(group);
        EditorUtility.DisplayDialog("Configure Level 01 Actors", "Level 01 actors are configured. Spawn objects remain intact. Review the instances and save manually when ready.", "OK");
    }

    private static void SetLoops(CharacterSpec spec)
    {
        string folder = CharacterArt + spec.ArtFolder + "/Animations/";
        string[] loopNames = { spec.Idle, spec.Locomotion };
        foreach (string name in loopNames) SetLoop(LoadClip(folder + name + ".anim"), true);
        string[] nonLoopNames = { spec.Action, spec.Death, spec.Hurt };
        foreach (string name in nonLoopNames)
            if (!string.IsNullOrEmpty(name)) SetLoop(LoadClip(folder + name + ".anim"), false);
    }

    private static void SetLoop(AnimationClip clip, bool loop)
    {
        if (clip == null) throw new InvalidOperationException("Expected Animation Clip was not found.");
        AnimationClipSettings settings = AnimationUtility.GetAnimationClipSettings(clip);
        if (settings.loopTime != loop)
        {
            settings.loopTime = loop;
            AnimationUtility.SetAnimationClipSettings(clip, settings);
            EditorUtility.SetDirty(clip);
        }
    }

    private static AnimatorController CreateOrRebuildController(CharacterSpec spec, string folder, string path)
    {
        EnsureFolder(folder + "/AnimatorControllers");
        AnimatorController controller = AssetDatabase.LoadAssetAtPath<AnimatorController>(path);
        if (controller == null) controller = AnimatorController.CreateAnimatorControllerAtPath(path);
        for (int parameterIndex = controller.parameters.Length - 1; parameterIndex >= 0; parameterIndex--)
            controller.RemoveParameter(parameterIndex);
        AnimatorStateMachine machine = controller.layers[0].stateMachine;
        foreach (ChildAnimatorState child in machine.states) machine.RemoveState(child.state);
        foreach (ChildAnimatorStateMachine child in machine.stateMachines) machine.RemoveStateMachine(child.stateMachine);

        controller.AddParameter("Speed", AnimatorControllerParameterType.Float);
        if (spec.Player) controller.AddParameter("Attack", AnimatorControllerParameterType.Trigger);
        else controller.AddParameter("Throw", AnimatorControllerParameterType.Trigger);
        if (!string.IsNullOrEmpty(spec.Hurt)) controller.AddParameter("Hurt", AnimatorControllerParameterType.Trigger);
        controller.AddParameter("Die", AnimatorControllerParameterType.Trigger);

        string animationFolder = folder + "/Animations/";
        AnimatorState idle = AddState(machine, "Idle", LoadClip(animationFolder + spec.Idle + ".anim"));
        AnimatorState move = AddState(machine, spec.Player ? "Run" : "Walk", LoadClip(animationFolder + spec.Locomotion + ".anim"));
        AnimatorState action = AddState(machine, spec.Player ? "Attack" : "Throw", LoadClip(animationFolder + spec.Action + ".anim"));
        AnimatorState hurt = string.IsNullOrEmpty(spec.Hurt) ? null : AddState(machine, "Hurt", LoadClip(animationFolder + spec.Hurt + ".anim"));
        AnimatorState death = AddState(machine, "Death", LoadClip(animationFolder + spec.Death + ".anim"));
        machine.defaultState = idle;

        AnimatorStateTransition die = machine.AddAnyStateTransition(death);
        die.AddCondition(AnimatorConditionMode.If, 0, "Die"); ConfigureAnyStateTransition(die);
        AnimatorStateTransition interruptedAction = machine.AddAnyStateTransition(action);
        interruptedAction.AddCondition(AnimatorConditionMode.If, 0, spec.Player ? "Attack" : "Throw"); ConfigureAnyStateTransition(interruptedAction);
        if (hurt != null)
        {
            AnimatorStateTransition interruptedHurt = machine.AddAnyStateTransition(hurt);
            interruptedHurt.AddCondition(AnimatorConditionMode.If, 0, "Hurt"); ConfigureAnyStateTransition(interruptedHurt);
        }
        AnimatorStateTransition toMove = idle.AddTransition(move);
        toMove.AddCondition(AnimatorConditionMode.Greater, 0.01f, "Speed"); ConfigureConditionalTransition(toMove);
        AnimatorStateTransition toIdle = move.AddTransition(idle);
        toIdle.AddCondition(AnimatorConditionMode.Less, 0.010001f, "Speed"); ConfigureConditionalTransition(toIdle);
        AddExitReturn(action, idle);
        if (hurt != null) AddExitReturn(hurt, idle);

        EditorUtility.SetDirty(controller);
        AssetDatabase.SaveAssets();
        return controller;
    }

    private static AnimatorState AddState(AnimatorStateMachine machine, string name, AnimationClip clip)
    {
        if (clip == null) throw new InvalidOperationException("Missing clip for state " + name);
        AnimatorState state = machine.AddState(name);
        state.motion = clip;
        state.writeDefaultValues = false;
        return state;
    }

    private static void ConfigureAnyStateTransition(AnimatorStateTransition transition)
    {
        transition.hasExitTime = false;
        transition.hasFixedDuration = true;
        transition.duration = 0f;
        transition.canTransitionToSelf = false;
        transition.interruptionSource = TransitionInterruptionSource.None;
    }

    private static void ConfigureConditionalTransition(AnimatorStateTransition transition)
    {
        transition.hasExitTime = false;
        transition.hasFixedDuration = true;
        transition.duration = TransitionDuration;
        transition.canTransitionToSelf = false;
    }

    private static void AddExitReturn(AnimatorState from, AnimatorState idle)
    {
        AnimatorStateTransition transition = from.AddTransition(idle);
        transition.hasExitTime = true;
        transition.exitTime = 1f;
        transition.hasFixedDuration = true;
        transition.duration = TransitionDuration;
        transition.canTransitionToSelf = false;
    }

    private static float[] CreatePrefab(CharacterSpec spec, AnimatorController controller)
    {
        EnsureFolder(ParentFolder(spec.PrefabPath));
        AnimationClip idle = LoadClip(CharacterArt + spec.ArtFolder + "/Animations/" + spec.Idle + ".anim");
        EditorCurveBinding[] bindings = AnimationUtility.GetObjectReferenceCurveBindings(idle);
        ObjectReferenceKeyframe[] keys = bindings.Length == 0 ? null : AnimationUtility.GetObjectReferenceCurve(idle, bindings[0]);
        Sprite initialSprite = keys != null && keys.Length > 0 ? keys[0].value as Sprite : null;
        if (initialSprite == null) throw new InvalidOperationException("Idle clip has no initial Sprite key: " + spec.Idle);
        float sourceHeight = initialSprite.bounds.size.y;
        float sourceWidth = initialSprite.bounds.size.x;
        if (sourceHeight <= 0 || sourceWidth <= 0) throw new InvalidOperationException("Idle sprite has invalid bounds: " + initialSprite.name);

        float visualScale = spec.TargetHeight / sourceHeight;
        float colliderHeight = spec.TargetHeight * 0.82f;
        float colliderWidth = Mathf.Min(sourceWidth * visualScale * spec.ColliderWidthFactor, spec.TargetHeight * 0.58f);
        GameObject root = new GameObject("Root");
        root.transform.localScale = Vector3.one;
        Rigidbody2D body = root.AddComponent<Rigidbody2D>();
        body.bodyType = RigidbodyType2D.Kinematic;
        body.gravityScale = 0;
        body.freezeRotation = true;
        CapsuleCollider2D collider = root.AddComponent<CapsuleCollider2D>();
        collider.size = new Vector2(colliderWidth, colliderHeight);
        collider.offset = new Vector2(0, colliderHeight * 0.5f);
        collider.direction = CapsuleDirection2D.Vertical;
        GameObject visual = new GameObject("Visual");
        visual.transform.SetParent(root.transform, false);
        visual.transform.localScale = new Vector3(visualScale, visualScale, 1);
        SpriteRenderer renderer = visual.AddComponent<SpriteRenderer>();
        renderer.sprite = initialSprite;
        renderer.sortingLayerName = SortingLayerExists("Actors") ? "Actors" : "Default";
        Animator animator = visual.AddComponent<Animator>();
        animator.runtimeAnimatorController = controller;
        PrefabUtility.SaveAsPrefabAsset(root, spec.PrefabPath);
        float colliderOffsetY = collider.offset.y;
        UnityEngine.Object.DestroyImmediate(root);
        return new[] { sourceHeight * visualScale, colliderWidth, colliderHeight, colliderOffsetY };
    }

    private static AnimationClip LoadClip(string path)
    {
        AnimationClip clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(path);
        if (clip == null) throw new InvalidOperationException("Animation Clip not found: " + path);
        return clip;
    }

    private static bool SortingLayerExists(string name)
    {
        foreach (SortingLayer layer in SortingLayer.layers) if (layer.name == name) return true;
        return false;
    }

    private static GameObject[] FindSceneObjects(Scene scene, string name)
    {
        var result = new List<GameObject>();
        foreach (GameObject gameObject in UnityEngine.Object.FindObjectsByType<GameObject>(FindObjectsInactive.Include))
            if (gameObject.scene == scene && gameObject.name == name) result.Add(gameObject);
        return result.ToArray();
    }

    private static string ParentFolder(string path) { return path.Substring(0, path.LastIndexOf('/')); }

    private static string F(float value) { return value.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture); }

    private static void EnsureFolder(string path)
    {
        if (AssetDatabase.IsValidFolder(path)) return;
        string parent = ParentFolder(path);
        EnsureFolder(parent);
        AssetDatabase.CreateFolder(parent, path.Substring(path.LastIndexOf('/') + 1));
    }
